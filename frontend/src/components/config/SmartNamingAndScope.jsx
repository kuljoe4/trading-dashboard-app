import React, { useEffect, useMemo, useRef, useState } from 'react';
import { RefreshCw, Target, Layers, Shield, Sparkles } from 'lucide-react';
import { cn } from '../ui/primitives';
import {
  STRATEGY_NAME_CHAR_LIMITS,
  generateSmartNameSuggestions,
  generateSmartStrategyName,
  getWatchlistScopeDescriptor,
  isGenericStrategyName,
  sanitizeStrategyLabel,
} from '../../utils/smartStrategyNaming.js';

export const SmartStrategyNameControl = React.memo(({
  cfg,
  setField,
  onInputFocus,
  compact = false,
  className,
}) => {
  const [charLimit, setCharLimit] = useState(() => {
    try {
      const saved = typeof localStorage !== 'undefined' && Number(localStorage.getItem('strategy_name_char_limit'));
      if (saved === 20 || saved === 28 || saved === 50) return saved;
    } catch (e) {}
    return STRATEGY_NAME_CHAR_LIMITS.STANDARD;
  });

  const currentLabel = String(cfg?.strategy_label || '');
  const [autoSync, setAutoSync] = useState(() => isGenericStrategyName(currentLabel));
  const lastAutoGeneratedRef = useRef('');

  const suggestions = useMemo(
    () => generateSmartNameSuggestions(cfg, charLimit),
    [cfg, charLimit],
  );

  const primarySuggestion = useMemo(
    () => generateSmartStrategyName(cfg, { maxLen: charLimit, style: 'standard' }),
    [cfg, charLimit],
  );

  // Keep strategy_label synced automatically when Auto-Name is ON (or if current label is still a generic placeholder)
  useEffect(() => {
    if (!autoSync) return;
    if (!primarySuggestion) return;
    if (
      isGenericStrategyName(currentLabel) ||
      currentLabel === lastAutoGeneratedRef.current
    ) {
      if (currentLabel !== primarySuggestion) {
        lastAutoGeneratedRef.current = primarySuggestion;
        setField('strategy_label', primarySuggestion);
      }
    }
  }, [autoSync, primarySuggestion, currentLabel, setField]);

  const handleSelectCharLimit = (limit) => {
    setCharLimit(limit);
    try {
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem('strategy_name_char_limit', String(limit));
      }
    } catch (e) {}
    if (autoSync) {
      const nextSmart = generateSmartStrategyName(cfg, { maxLen: limit, style: 'standard' });
      lastAutoGeneratedRef.current = nextSmart;
      setField('strategy_label', nextSmart);
    } else if (currentLabel.length > limit) {
      setField('strategy_label', sanitizeStrategyLabel(currentLabel, limit));
    }
  };

  const handleToggleAutoSync = () => {
    const next = !autoSync;
    setAutoSync(next);
    if (next && primarySuggestion) {
      lastAutoGeneratedRef.current = primarySuggestion;
      setField('strategy_label', primarySuggestion);
    }
  };

  const handleApplySuggestion = (val) => {
    const clean = sanitizeStrategyLabel(val, charLimit);
    lastAutoGeneratedRef.current = clean;
    setField('strategy_label', clean);
  };

  const charCount = currentLabel.length;
  const isNearLimit = charCount >= charLimit - 3;

  return (
    <div className={cn('flex flex-col gap-2 w-full min-w-0 max-w-full overflow-hidden', className)}>
      {/* Top Row: Label + Auto-Name Toggle + Character Limit Picker */}
      <div className="flex items-center justify-between gap-1.5 flex-wrap min-w-0">
        <div className="flex items-center gap-1.5 min-w-0">
          <label
            htmlFor="smart-strategy-label-input"
            className="text-[11px] font-semibold text-dim truncate"
          >
            Strategy Name
          </label>
          <button
            type="button"
            onClick={handleToggleAutoSync}
            title={
              autoSync
                ? 'Dynamic Smart Naming is ON: Name updates automatically when you change signals, timeframes, or watchlist mode'
                : 'Click to enable automatic smart naming from strategy parameters'
            }
            className={cn(
              'h-5 px-1.5 sm:px-2 rounded-md text-[10px] font-semibold inline-flex items-center gap-1 border transition-colors cursor-pointer whitespace-nowrap shrink-0',
              autoSync
                ? 'bg-accent/15 border-accent/40 text-accent'
                : 'bg-surface/60 border-border/60 text-dim hover:text-text hover:border-border',
            )}
          >
            <Sparkles size={10} className="shrink-0" />
            <span>{autoSync ? 'Auto: On' : 'Auto: Off'}</span>
          </button>
        </div>

        {/* Character Limit Controls & Counter */}
        <div className="flex items-center gap-1 text-[10px] font-mono tabular-nums shrink-0">
          <span
            className={cn(
              'font-semibold',
              charCount > charLimit
                ? 'text-red'
                : isNearLimit
                  ? 'text-amber'
                  : 'text-dim',
            )}
            title={`Character count (${charCount} of ${charLimit} max)`}
          >
            {charCount}/{charLimit}
          </span>
          <div
            className="inline-flex items-center rounded-md bg-surface/70 border border-border/60 p-0.5 gap-0.5"
            role="group"
            aria-label="Strategy name character limit"
          >
            {[
              { label: '20c', val: STRATEGY_NAME_CHAR_LIMITS.COMPACT, title: 'Compact (20 chars max)' },
              { label: '28c', val: STRATEGY_NAME_CHAR_LIMITS.STANDARD, title: 'Standard (28 chars max)' },
              { label: '50c', val: STRATEGY_NAME_CHAR_LIMITS.MAX, title: 'Max allowed (50 chars max)' },
            ].map((opt) => (
              <button
                key={opt.val}
                type="button"
                onClick={() => handleSelectCharLimit(opt.val)}
                title={opt.title}
                className={cn(
                  'px-1.5 py-0.5 rounded text-[9.5px] font-mono font-semibold transition-colors cursor-pointer whitespace-nowrap',
                  charLimit === opt.val
                    ? 'bg-accent text-background font-bold'
                    : 'text-dim hover:text-text',
                )}
              >
                {opt.label}
              </button>
            ))}
          </div>
        </div>
      </div>

      {/* Input + One-Click Smart Regenerate */}
      <div className="relative flex items-center gap-1.5 w-full min-w-0">
        <input
          id="smart-strategy-label-input"
          name="strategy_label"
          type="text"
          maxLength={charLimit}
          value={currentLabel}
          onFocus={onInputFocus}
          onChange={(e) => {
            const raw = e.target.value;
            const sanitized = sanitizeStrategyLabel(raw, charLimit);
            setAutoSync(false);
            setField('strategy_label', sanitized);
          }}
          placeholder={primarySuggestion || 'e.g. Top hl 1h'}
          className="flex-1 min-w-0 w-full min-h-[34px] sm:min-h-[36px] bg-surface border border-border/80 rounded-lg px-2.5 sm:px-3 py-1.5 text-xs font-mono font-bold text-text focus:border-accent focus:outline-none focus-visible:ring-1 focus-visible:ring-accent transition-colors"
        />
        <button
          type="button"
          onClick={() => {
            setAutoSync(true);
            handleApplySuggestion(primarySuggestion);
          }}
          title={`Generate smart name (${primarySuggestion})`}
          aria-label="Generate smart strategy name"
          className="min-h-[34px] sm:min-h-[36px] px-2.5 rounded-lg border border-border/80 bg-surface hover:border-accent/50 hover:text-accent text-dim inline-flex items-center justify-center gap-1 text-[11px] font-semibold transition-colors cursor-pointer shrink-0 whitespace-nowrap"
        >
          <RefreshCw size={12} className="shrink-0" />
          <span className="hidden sm:inline">Smart Name</span>
        </button>
      </div>

      {/* Instant 1-Click Formula Suggestions (Mobile-First Grid prevents horizontal overflow) */}
      {suggestions.length > 0 && (
        <div className="grid grid-cols-3 sm:flex sm:items-center sm:flex-wrap gap-1.5 w-full min-w-0 text-[10px] sm:text-[10.5px]">
          <span className="hidden sm:inline text-dim font-medium shrink-0">Suggestions:</span>
          {suggestions.map((sug) => {
            const isActive = currentLabel === sug.value;
            return (
              <button
                key={sug.id}
                type="button"
                onClick={() => handleApplySuggestion(sug.value)}
                title={`Apply ${sug.label}: "${sug.value}" (${sug.value.length} chars)`}
                className={cn(
                  'min-w-0 w-full sm:w-auto px-2 py-1 sm:py-0.5 rounded-md font-mono text-[10px] sm:text-[10.5px] border transition-colors cursor-pointer truncate text-center sm:max-w-[200px]',
                  isActive
                    ? 'bg-accent/15 border-accent/40 text-accent font-bold'
                    : 'bg-background/60 border-border/50 text-dim hover:text-text hover:border-border',
                )}
              >
                {sug.value}
              </button>
            );
          })}
        </div>
      )}
    </div>
  );
});
SmartStrategyNameControl.displayName = 'SmartStrategyNameControl';

export const WatchlistScopeSelector = React.memo(({
  cfg,
  setField,
  onOpenWatchlistSection,
  compact = false,
}) => {
  const scope = useMemo(() => getWatchlistScopeDescriptor(cfg), [cfg]);
  const discoveryMode = String(cfg?.discovery_mode || 'volume').toLowerCase();
  const entrySide = String(cfg?.entry_side || 'both').toLowerCase();
  const watchlistSize = Number(cfg?.watchlist_size ?? 15);
  const watchlistOffset = Number(cfg?.watchlist_offset ?? 0);

  const handleSelectScopeMode = (targetMode) => {
    if (targetMode === 'dynamic_solo') {
      setField('global_scanner_enabled', true);
      setField('watchlist_size', 1);
      if (discoveryMode === 'volume') {
        // Default to Gainers for Long or Losers for Short when switching to Solo Leader
        if (entrySide === 'short') setField('discovery_mode', 'loss_pct');
        else setField('discovery_mode', 'change_pct');
      }
    } else if (targetMode === 'dynamic_multi') {
      setField('global_scanner_enabled', true);
      if (Number(cfg?.watchlist_size) <= 1) {
        setField('watchlist_size', 15);
      }
      setField('watchlist_offset', 0);
    } else if (targetMode === 'static') {
      setField('global_scanner_enabled', false);
      if (onOpenWatchlistSection) {
        onOpenWatchlistSection();
      }
    }
  };

  const applySoloPreset = (preset) => {
    setField('global_scanner_enabled', true);
    setField('watchlist_size', 1);
    setField('discovery_mode', preset.discovery_mode);
    setField('entry_side', preset.entry_side);
    setField('watchlist_offset', preset.watchlist_offset);
  };

  const soloPresets = [
    {
      id: 'top_gainer_1',
      label: '#1 Top Gainer · Long',
      discovery_mode: 'change_pct',
      entry_side: 'long',
      watchlist_offset: 0,
      active:
        scope.mode === 'dynamic_solo' &&
        discoveryMode === 'change_pct' &&
        entrySide === 'long' &&
        watchlistOffset === 0,
    },
    {
      id: 'top_loser_1',
      label: '#1 Top Loser · Short',
      discovery_mode: 'loss_pct',
      entry_side: 'short',
      watchlist_offset: 0,
      active:
        scope.mode === 'dynamic_solo' &&
        (discoveryMode === 'loss_pct' || discoveryMode === 'losers') &&
        entrySide === 'short' &&
        watchlistOffset === 0,
    },
    {
      id: 'runner_up_2',
      label: `#2 ${discoveryMode === 'loss_pct' ? 'Loser' : 'Gainer'} (Offset 1)`,
      discovery_mode: discoveryMode === 'loss_pct' ? 'loss_pct' : 'change_pct',
      entry_side: discoveryMode === 'loss_pct' ? 'short' : 'long',
      watchlist_offset: 1,
      active: scope.mode === 'dynamic_solo' && watchlistOffset === 1,
    },
    {
      id: 'abs_mover_1',
      label: '#1 Abs Mover · Both',
      discovery_mode: 'abs_change_pct',
      entry_side: 'both',
      watchlist_offset: 0,
      active:
        scope.mode === 'dynamic_solo' &&
        discoveryMode === 'abs_change_pct' &&
        watchlistOffset === 0,
    },
  ];

  const multiCount = watchlistSize > 1 ? watchlistSize : 15;

  return (
    <div className="flex flex-col gap-2.5 p-2.5 sm:p-3 rounded-xl border border-border/70 bg-background/40 w-full min-w-0 max-w-full overflow-hidden">
      {/* Header & Segmented Mode Switcher */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 min-w-0">
        <div className="flex flex-col min-w-0">
          <div className="flex items-center justify-between sm:justify-start gap-1.5 flex-wrap min-w-0">
            <span className="text-xs font-bold text-text truncate">{scope.title}</span>
            <span className="text-[10.5px] sm:text-[11px] font-mono tabular-nums text-accent font-semibold truncate">
              {scope.badge}
            </span>
          </div>
          <span className="text-[10.5px] sm:text-[11px] text-dim leading-snug break-words">
            {scope.subtitle}
          </span>
        </div>

        {/* 3-Way Segmented Control: Mobile-first 3-col grid on phones, inline-flex on sm+ */}
        <div
          className="grid grid-cols-3 sm:inline-flex items-center p-0.5 sm:p-1 rounded-lg bg-surface border border-border/70 gap-1 w-full sm:w-auto min-w-0 shrink-0"
          role="group"
          aria-label="Watchlist Scope Mode"
        >
          <button
            type="button"
            onClick={() => handleSelectScopeMode('dynamic_solo')}
            className={cn(
              'min-w-0 px-1.5 sm:px-2.5 py-1 rounded-md text-[10.5px] sm:text-[11px] font-semibold inline-flex items-center justify-center gap-1 sm:gap-1.5 transition-colors cursor-pointer truncate',
              scope.mode === 'dynamic_solo'
                ? 'bg-accent text-background font-bold shadow-xs'
                : 'text-dim hover:text-text',
            )}
          >
            <Target size={11} className="shrink-0" />
            <span className="truncate">
              <span className="sm:hidden">Solo (1)</span>
              <span className="hidden sm:inline">Solo Leader (1)</span>
            </span>
          </button>

          <button
            type="button"
            onClick={() => handleSelectScopeMode('dynamic_multi')}
            className={cn(
              'min-w-0 px-1.5 sm:px-2.5 py-1 rounded-md text-[10.5px] sm:text-[11px] font-semibold inline-flex items-center justify-center gap-1 sm:gap-1.5 transition-colors cursor-pointer truncate',
              scope.mode === 'dynamic_multi'
                ? 'bg-accent text-background font-bold shadow-xs'
                : 'text-dim hover:text-text',
            )}
          >
            <Layers size={11} className="shrink-0" />
            <span className="truncate">
              <span className="sm:hidden">Multi ({multiCount})</span>
              <span className="hidden sm:inline">Multi-Pair ({multiCount})</span>
            </span>
          </button>

          <button
            type="button"
            onClick={() => handleSelectScopeMode('static')}
            className={cn(
              'min-w-0 px-1.5 sm:px-2.5 py-1 rounded-md text-[10.5px] sm:text-[11px] font-semibold inline-flex items-center justify-center gap-1 sm:gap-1.5 transition-colors cursor-pointer truncate',
              scope.isStatic
                ? 'bg-accent text-background font-bold shadow-xs'
                : 'text-dim hover:text-text',
            )}
          >
            <Shield size={11} className="shrink-0" />
            <span className="truncate">Static</span>
          </button>
        </div>
      </div>

      {/* Contextual Sub-Bar: Distinct UI when Solo Leader (1 Pair) vs Multi-Pair is active */}
      {scope.mode === 'dynamic_solo' && (
        <div className="pt-2 border-t border-border/40 flex flex-col gap-2 min-w-0">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-0.5 sm:gap-2 min-w-0 text-[10.5px] sm:text-[11px]">
            <span className="font-semibold text-text/90 truncate">
              Quick Solo Target Presets:
            </span>
            <span className="text-dim font-mono text-[9.5px] sm:text-[10px] truncate">
              15s Leaderboard Refresh · Pullback Pinning · Top-3 Kline Pre-Warm
            </span>
          </div>
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-1.5 w-full min-w-0">
            {soloPresets.map((p) => (
              <button
                key={p.id}
                type="button"
                onClick={() => applySoloPreset(p)}
                className={cn(
                  'min-w-0 w-full px-2 sm:px-2.5 py-1.5 rounded-lg text-[10px] sm:text-[11px] font-mono font-semibold border text-left transition-colors cursor-pointer truncate',
                  p.active
                    ? 'bg-accent/15 border-accent/50 text-accent font-bold'
                    : 'bg-surface/60 border-border/50 text-dim hover:text-text hover:border-border',
                )}
              >
                {p.label}
              </button>
            ))}
          </div>
        </div>
      )}

      {scope.mode === 'dynamic_multi' && !compact && (
        <div className="pt-2 border-t border-border/40 flex items-center justify-between gap-2 flex-wrap text-[11px] min-w-0">
          <span className="text-dim">Pool Size Presets:</span>
          <div className="flex items-center gap-1.5 flex-wrap min-w-0">
            {[5, 10, 15, 25, 50].map((sz) => (
              <button
                key={sz}
                type="button"
                onClick={() => setField('watchlist_size', sz)}
                className={cn(
                  'px-2 py-0.5 rounded-md font-mono text-[10.5px] border transition-colors cursor-pointer whitespace-nowrap',
                  watchlistSize === sz
                    ? 'bg-accent/15 border-accent/40 text-accent font-bold'
                    : 'bg-surface/60 border-border/50 text-dim hover:text-text',
                )}
              >
                Top {sz}
              </button>
            ))}
          </div>
        </div>
      )}
    </div>
  );
});
WatchlistScopeSelector.displayName = 'WatchlistScopeSelector';
